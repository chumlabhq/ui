/**
 * Generates src/styles/tokens.css - the stylesheet consumers import - from the
 * --cl-* token blocks in src/index.css.
 *
 * The library and the docs site must not drift: index.css is where tokens are
 * authored and where the docs read them from, so the published file is derived
 * rather than maintained in parallel.
 *
 * The output ships UNCOMPILED on purpose. Its `@theme` block is what lets a
 * consumer's Tailwind generate the cl-* utilities the components emit; running
 * Tailwind over it at publish time would consume `@theme` and strip the one
 * thing consumers need.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = resolve(root, "src/index.css");
const OUT = resolve(root, "src/styles/tokens.css");

// A real declaration, not a comment fragment that happens to start with --cl-.
const DECL = /^--[a-z0-9-]+\s*:\s*[^;]+;$/;

const lines = readFileSync(SRC, "utf8").split("\n").map((l) => l.trim());

/**
 * Declarations matching `prefix` inside the brace-block opened by `selector`.
 *
 * index.css mentions these selectors in prose too (and reopens
 * `[data-theme="light"]` inside a media query with no --cl-* in it), so a
 * loose match lands on a comment or an empty block. Only a line that actually
 * OPENS a block counts, and of those, the first one carrying the tokens wins.
 */
function blockDecls(selector, prefix) {
  const openers = lines
    .map((l, i) => [l, i])
    .filter(([l]) => l.endsWith("{") && l.slice(0, -1).trim().endsWith(selector));

  if (!openers.length) throw new Error(`build-tokens: no block opens with: ${selector}`);

  for (const [, start] of openers) {
    const out = [];
    for (let i = start + 1; i < lines.length && lines[i] !== "}"; i++) {
      if (DECL.test(lines[i]) && prefix.test(lines[i])) out.push(lines[i]);
    }
    if (out.length) return out;
  }
  return [];
}

const dark = blockDecls(':root[data-theme="dark"]', /^--cl-/);
const light = blockDecls(':root[data-theme="light"]', /^--cl-/);
const theme = blockDecls("@theme inline", /^--(color|radius|shadow)-cl-/);

const names = (ds) => new Set(ds.map((d) => d.split(":")[0].trim()));

// A dark token with no light counterpart would silently keep its dark value in
// a light-themed consumer app - a bug that only shows up visually.
const darkNames = names(dark);
const lightNames = names(light);
const orphaned = [...darkNames].filter((n) => !lightNames.has(n));
const unpaired = [...lightNames].filter((n) => !darkNames.has(n));

// A @theme mapping pointing at a token that does not exist yields a utility
// that resolves to nothing - exactly the failure this file exists to prevent.
const dangling = theme
  .map((t) => t.match(/var\((--cl-[a-z0-9-]+)\)/)?.[1])
  .filter((ref) => ref && !darkNames.has(ref));

const problems = [
  orphaned.length && `dark tokens with no light value: ${orphaned.join(", ")}`,
  unpaired.length && `light tokens with no dark value: ${unpaired.join(", ")}`,
  dangling.length && `@theme maps to undefined tokens: ${dangling.join(", ")}`,
  !dark.length && "no dark tokens found",
  !theme.length && "no @theme mappings found",
].filter(Boolean);

if (problems.length) {
  console.error("build-tokens FAILED:");
  for (const p of problems) console.error(`  - ${p}`);
  process.exit(1);
}

const indent = (ds) => ds.map((d) => `  ${d}`).join("\n");

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(
  OUT,
  `/**
 * @chumlab/ui design tokens.
 *
 * GENERATED by scripts/build-tokens.mjs from src/index.css - do not edit.
 *
 * Ships as SOURCE CSS, deliberately uncompiled: the \`@theme\` block below is what
 * lets a consumer's Tailwind generate the \`cl-*\` utilities the components emit.
 *
 * In the consumer's stylesheet:
 *
 *   @import "tailwindcss";
 *   @import "@chumlab/ui/style.css";
 *   @source "../node_modules/@chumlab/ui/dist";
 */

/* Dark is the default: it is the surface the components were designed against.
 *
 * Both switches are honoured, because the components' \`dark:\` utilities key off
 * the \`.dark\` class (see the @custom-variant in styles.css). If tokens listened
 * only to [data-theme], a consumer setting class="dark" would get dark utilities
 * with light tokens - or the reverse - which is unreadable either way. */
:root,
:root.dark,
:root[data-theme="dark"] {
${indent(dark)}
}

:root.light,
:root[data-theme="light"] {
${indent(light)}
}

@theme inline {
${indent(theme)}
}
`,
);

console.log(`✓ tokens.css: ${dark.length} dark, ${light.length} light, ${theme.length} @theme mappings`);
